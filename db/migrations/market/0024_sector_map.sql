  isin          TEXT NOT NULL,
  sm_industry   TEXT NOT NULL,
  first_at      TEXT NOT NULL,
  last_at       TEXT NOT NULL,
  first_ref     TEXT NOT NULL,
  PRIMARY KEY (isin, sm_industry)
);
